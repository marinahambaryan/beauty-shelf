#!/usr/bin/env bash
# One-shot local setup for Beauty Shelf (macOS / Linux).
#   1. checks Node + Docker (OrbStack or Docker Desktop)
#   2. installs npm dependencies
#   3. starts the local Supabase stack and applies migrations + seed
#   4. writes .env.local with the local API URL and anon key
#   5. runs typecheck/lint/unit tests and the database test suite
# Safe to re-run. Usage:  ./scripts/setup-local.sh   (add --skip-tests to go faster)
set -euo pipefail
cd "$(dirname "$0")/.."

SKIP_TESTS=0
[ "${1:-}" = "--skip-tests" ] && SKIP_TESTS=1

step() { printf '\n\033[1;35m▸ %s\033[0m\n' "$1"; }
fail() { printf '\n\033[1;31m✗ %s\033[0m\n' "$1" >&2; exit 1; }

step "Checking prerequisites"
command -v node >/dev/null || fail "Node.js not found. Install Node 20+ (e.g. 'nvm install 22')."
NODE_MAJOR=$(node -p 'process.versions.node.split(".")[0]')
[ "$NODE_MAJOR" -ge 20 ] || fail "Node $NODE_MAJOR found; Node 20+ is required."
command -v docker >/dev/null || fail "Docker not found. Start OrbStack (or Docker Desktop) and re-run."
docker info >/dev/null 2>&1 || fail "Docker isn't running. Open OrbStack (or Docker Desktop), wait until it's ready, then re-run."
echo "Node $(node -v), Docker OK"

step "Installing dependencies"
npm install --no-audit --no-fund

step "Starting local Supabase (first run downloads images — a few minutes)"
if ! npx supabase status >/dev/null 2>&1; then
  if ! npx supabase start; then
    # Don't leave a half-migrated database volume behind: the next run would fail with
    # misleading "already exists" errors instead of the real one.
    npx supabase stop --no-backup >/dev/null 2>&1 || true
    fail "Supabase failed to start — the FIRST error above is the real cause. The partial local database was wiped, so re-running is safe."
  fi
fi

step "Applying migrations and seed catalog"
npx supabase db reset
# Catalogue packshots in supabase/catalog-images (bucket declared in config.toml).
npx supabase seed buckets

step "Writing .env.local"
STATUS_ENV=$(npx supabase status -o env 2>/dev/null)
get() { printf '%s\n' "$STATUS_ENV" | sed -n "s/^$1=\"\{0,1\}\([^\"]*\)\"\{0,1\}$/\1/p" | head -n1; }
API_URL=$(get API_URL)
ANON_KEY=$(get ANON_KEY)
[ -n "$ANON_KEY" ] || ANON_KEY=$(get PUBLISHABLE_KEY)
[ -n "$API_URL" ] && [ -n "$ANON_KEY" ] || fail "Couldn't read API URL / anon key from 'supabase status'. Copy them into .env.local by hand (see .env.example)."
cat > .env.local <<EOF
# Generated by scripts/setup-local.sh for the LOCAL Supabase stack.
EXPO_PUBLIC_SUPABASE_URL=$API_URL
EXPO_PUBLIC_SUPABASE_ANON_KEY=$ANON_KEY
EOF
echo "Wrote .env.local → $API_URL"

if [ "$SKIP_TESTS" -eq 0 ]; then
  step "Typecheck, lint and unit tests"
  npm run check

  step "Database tests against the local stack"
  DB_URL=$(get DB_URL)
  DATABASE_URL="${DB_URL:-postgresql://postgres:postgres@127.0.0.1:55322/postgres}" SKIP_DB_BUILD=1 npm run test:db
  # Tests create throwaway users; reset so you start from a clean, seeded database.
  npx supabase db reset >/dev/null
fi

STUDIO=$(get STUDIO_URL)
cat <<EOF

$(printf '\033[1;32m✓ Beauty Shelf is set up.\033[0m')

  Start the app:      npm start        then press  i (iOS simulator)  a (Android)  w (web)
  Supabase Studio:    ${STUDIO:-http://127.0.0.1:55323}
  Stop the backend:   npx supabase stop

  Phone on the same Wi-Fi? 127.0.0.1 points at the phone itself — set
  EXPO_PUBLIC_SUPABASE_URL in .env.local to http://<your-mac-LAN-IP>:55321 instead.
EOF
